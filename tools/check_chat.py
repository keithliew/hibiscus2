#!/usr/bin/env python3
"""Keep the chat assistant inside the hibiscus2.com compliance rules.

1. Writes chat/banned.js from the ```banned block in approved-facts.md, so the
   live filter in functions/api/chat.js blocks exactly what the page scan blocks.
2. Scans what a visitor can see from the chat: the facts the assistant may use,
   its fixed fallback replies, and the chat window's own text (hibiscus2-site/js/chat.js).

Usage: python3 tools/check_chat.py      (exit code 1 on a banned term)
Run it after any change to approved-facts.md, chat/facts.js or js/chat.js.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FACTS_MD = ROOT / "approved-facts.md"
FACTS_JS = ROOT / "chat" / "facts.js"
BANNED_JS = ROOT / "chat" / "banned.js"
WIDGET_JS = ROOT / "hibiscus2-site" / "js" / "chat.js"


def rules(kind):
    block = re.search(rf"```{kind}\n(.*?)```", FACTS_MD.read_text(encoding="utf-8"), re.S)
    if not block:
        sys.exit(f"approved-facts.md has no ```{kind} block")
    return [l.strip() for l in block.group(1).splitlines() if l.strip()]


def write_banned(banned):
    body = ",\n".join(f"  new RegExp({json.dumps(p)}, \"i\")" for p in banned)
    BANNED_JS.write_text(
        "// GENERATED by tools/check_chat.py from approved-facts.md (BANNED AND WATCH TERMS). Do not edit.\n"
        f"export const BANNED = [\n{body},\n];\n",
        encoding="utf-8",
    )


def visible_chat_text():
    src = FACTS_JS.read_text(encoding="utf-8")
    facts = src.split("FACTS YOU MAY USE", 1)[1].split("OUTPUT\n", 1)[0]
    parts = [("chat/facts.js facts", facts)]
    for name in ("SAFE", "BUSY", "OPEN_HOUSE"):
        m = re.search(rf"const {name} = (\{{.*?\n\}}|`.*?`);", src, re.S)
        parts.append((f"chat/facts.js {name}", m.group(1) if m else ""))
    w = WIDGET_JS.read_text(encoding="utf-8")
    m = re.search(r"// TEXT START(.*?)// TEXT END", w, re.S)
    parts.append(("js/chat.js visitor text", m.group(1) if m else w))
    return parts


def main():
    banned, watch = rules("banned"), rules("watch")
    write_banned(banned)
    bad = 0
    for where, text in visible_chat_text():
        for line in text.splitlines():
            for p in banned:
                if re.search(p, line, re.I):
                    print(f"BANNED  {where}: /{p}/ in: {line.strip()[:120]}")
                    bad += 1
            for p in watch:
                if re.search(p, line, re.I):
                    print(f"watch   {where}: /{p}/ in: {line.strip()[:120]}")
    print(f"chat/banned.js written ({len(banned)} patterns). {bad} banned hit(s).")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
