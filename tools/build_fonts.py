#!/usr/bin/env python3
"""Self-host the site's two Google fonts so pages make no request to Google for fonts.

    python3 -I tools/build_fonts.py

Reads the same Google Fonts stylesheet the pages used to link, keeps every subset whose
unicode-range covers a character that appears in a page (so glyph coverage is unchanged),
downloads those woff2 files into hibiscus2-site/fonts/ and writes hibiscus2-site/css/fonts.css
with the same @font-face rules (font-display: swap) pointing at the local files.
Re-run only when the fonts or weights change. Standard library only.
"""
import re
import urllib.request
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent / "hibiscus2-site"
CSS_URL = "https://fonts.googleapis.com/css2?family=Playfair+Display:wght@500;600&family=Inter:wght@400;600;700&display=swap"
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30).read()


def in_range(cp, rng):
    for part in rng.split(","):
        part = part.strip().upper().replace("U+", "")
        lo, _, hi = part.partition("-")
        if "?" in lo:
            lo, hi = lo.replace("?", "0"), lo.replace("?", "F")
        if int(lo, 16) <= cp <= int(hi or lo, 16):
            return True
    return False


def main():
    used = set()
    for p in SITE.rglob("*"):
        if p.suffix in (".html", ".js") and not p.name.startswith("._"):
            used |= {ord(c) for c in p.read_text(encoding="utf-8")}
    css = get(CSS_URL).decode()
    out, files = [], {}
    for sub, body in re.findall(r"/\* ([\w-]+) \*/\s*@font-face\s*{([^}]*)}", css):
        rng = re.search(r"unicode-range:\s*([^;]+);", body).group(1)
        if not any(in_range(cp, rng) for cp in used):
            continue
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        weight = re.search(r"font-weight:\s*([\d ]+);", body).group(1).strip()
        url = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)", body).group(1)
        slug = re.sub(r"[^a-z0-9]+", "-", family.lower()).strip("-")
        if url not in files:  # a variable font returns one file for every weight
            files[url] = f"{slug}-{sub}.woff2"
            (SITE / "fonts").mkdir(exist_ok=True)
            (SITE / "fonts" / files[url]).write_bytes(get(url))
        out.append(f"/* {sub} */\n@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;"
                   f"src:url(/fonts/{files[url]}) format('woff2');unicode-range:{rng}}}")
    for slug in ("playfairdisplay", "inter"):
        (SITE / "fonts" / f"LICENSE-{slug}.txt").write_bytes(get(f"https://raw.githubusercontent.com/google/fonts/main/ofl/{slug}/OFL.txt"))
    (SITE / "css" / "fonts.css").write_text("/* Generated by tools/build_fonts.py. Do not edit by hand. */\n" + "\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(out)} @font-face rules, {len(files)} files:", ", ".join(sorted(files.values())))


if __name__ == "__main__":
    main()
