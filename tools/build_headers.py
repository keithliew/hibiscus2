#!/usr/bin/env python3
"""Write hibiscus2-site/_headers: the security headers, cache rules and the staging noindex rule.

    python3 -I tools/build_headers.py           # write the file
    python3 -I tools/build_headers.py --check   # exit 1 if the file is out of date

The Content-Security-Policy is sent as Report-Only: browsers log what it would block and block
nothing. It lists the outside hosts the pages use today (Google Tag Manager, GA4, Google Ads,
Web3Forms, the YouTube and Google Maps embeds) and a hash for each inline script found in the
pages, so re-run this whenever an inline script or an outside host changes. Standard library only.

Left out on purpose (decide before enforcing): Cross-Origin-Opener-Policy (same-origin cuts the
link Google Tag Assistant's preview window relies on) and Cross-Origin-Resource-Policy.
"""
import base64
import hashlib
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent / "hibiscus2-site"
GOOGLE_TAGS = "https://*.googletagmanager.com https://*.google-analytics.com https://*.analytics.google.com https://*.g.doubleclick.net https://*.google.com https://*.google.com.my https://www.googleadservices.com https://pagead2.googlesyndication.com"


def inline_script_hashes():
    hashes = set()
    for p in SITE.rglob("*.html"):
        if p.name.startswith("._"):
            continue
        for attrs, body in re.findall(r"<script\b([^>]*)>(.*?)</script>", p.read_text(encoding="utf-8"), re.S):
            if "src=" in attrs or "application/ld+json" in attrs or not body.strip():
                continue
            hashes.add("'sha256-" + base64.b64encode(hashlib.sha256(body.encode()).digest()).decode() + "'")
    return sorted(hashes)


def build():
    csp = {
        "default-src": "'none'",
        "script-src": "'self' " + " ".join(inline_script_hashes()) + " " + GOOGLE_TAGS,
        "style-src": "'self' 'unsafe-inline'",
        "font-src": "'self'",
        "img-src": "'self' data: https://i.ytimg.com " + GOOGLE_TAGS,
        "connect-src": "'self' https://api.web3forms.com " + GOOGLE_TAGS,
        "frame-src": "https://www.googletagmanager.com https://td.doubleclick.net https://www.google.com https://www.youtube.com https://www.youtube-nocookie.com",
        "manifest-src": "'self'",
        "form-action": "'self' https://api.web3forms.com",
        "base-uri": "'self'",
        "object-src": "'none'",
        "frame-ancestors": "'none'",
    }
    policy = "; ".join(f"{k} {v}" for k, v in csp.items())
    return f"""# Generated by tools/build_headers.py. Do not edit by hand.
# Cloudflare Pages response headers: https://developers.cloudflare.com/pages/configuration/headers/

/*
  Content-Security-Policy-Report-Only: {policy}
  Strict-Transport-Security: max-age=15552000
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), browsing-topics=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()
  X-Permitted-Cross-Domain-Policies: none

# Keep the Cloudflare Pages copies (hibiscus2.pages.dev and branch previews) out of search results.
# hibiscus2.com itself is unaffected. functions/robots.txt.js also serves a disallow-all robots.txt there.
https://:project.pages.dev/*
  X-Robots-Tag: noindex

https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex

# Files whose content never changes under the same name
/fonts/*
  Cache-Control: public, max-age=31536000, immutable
/images/r/*
  Cache-Control: public, max-age=31536000, immutable
"""


def main():
    new, path = build(), SITE / "_headers"
    if "--check" in sys.argv:
        sys.exit(0 if path.read_text(encoding="utf-8") == new else "_headers is out of date: run python3 -I tools/build_headers.py")
    path.write_text(new, encoding="utf-8")
    print("wrote", path, "with", len(inline_script_hashes()), "inline-script hashes")


if __name__ == "__main__":
    main()
